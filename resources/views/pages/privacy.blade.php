                    <h2 class="text-xl font-bold text-slate-900 flex items-center space-x-2">
                        <span class="text-blue-600 font-mono text-sm">05.</span>
                        <span>On-Device Storage, Sandboxing &amp; Hardware Encryption</span>
                    </h2>
                    <p>
                        PocketSQL adheres to strict Android security sandboxing standards:
                    </p>
                    <ul class="list-disc pl-5 space-y-2 text-slate-600">
                        <li>
                            <strong>Internal App Sandbox:</strong> All raw database files are stored inside internal scoped application storage (<code class="bg-slate-100 px-1 py-0.5 rounded font-mono text-xs">/data/data/app.pocketsql.database/databases/</code>). Android OS security prevents any other non-root application from accessing, reading, or tampering with these files.
                        </li>
                        <li>
                            <strong>Hardware-Backed Keystore:</strong> Master application secrets and encrypted authentication tokens are secured with AES-256 GCM backed by the <strong>Android Keystore System</strong> (utilizing hardware TEE / StrongBox where available on your device).
                        </li>
                        <li>
                            <strong>Optional At-Rest Encryption (SQLCipher):</strong> Users may activate native 256-bit AES encryption across the entire database file, rendering physical storage dumps unreadable without the passphrase.
                        </li>
                    </ul>
                </section>

